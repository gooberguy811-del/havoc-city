const { chromium, devices } = require('playwright');
const fs = require('fs');
const SP = process.argv[2];
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ ...devices['iPhone 13 landscape'] });
  const page = await ctx.newPage();
  const errs = [];
  page.on('pageerror', e => errs.push('pageerror: ' + e.message));
  page.on('console', m => { if (m.type() === 'error') errs.push(m.text()); });
  await page.route('**/three.min.js', r => r.fulfill({ path: SP + '/vendor/package/build/three.min.js', contentType: 'application/javascript' }));
  await page.route('**/fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
  await page.route('**/fonts.gstatic.com/**', r => r.abort());
  await page.goto('file://' + SP + '/test/index.html'); await page.waitForTimeout(1000);
  await page.evaluate(() => { Object.assign(window.__havoc.settings, { map: 'neon', trafficDensity: 0, pedDensity: 0, slowmo: 'off', quality: 'low' }); });
  await page.evaluate(() => { document.querySelector('.mapcard[data-map="neon"]').click(); document.querySelector('#playBtn').click(); });
  await page.waitForTimeout(2500);
  await page.tap('#minimap'); await page.waitForTimeout(500);
  const open1 = await page.evaluate(() => window.__havoc.BM.open);
  await page.screenshot({ path: SP + '/test/m3-map.png' });
  await page.tap('#bmClose'); await page.waitForTimeout(300);
  console.log('map tap open', open1, 'after X', await page.evaluate(() => [window.__havoc.BM.open, !document.querySelector('#touch').hidden]));
  const tap = k => page.evaluate(k => { const b = document.querySelector(`#touch [data-k=${k}]`); b.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, pointerId: 9, pointerType: 'touch' })); b.dispatchEvent(new PointerEvent('pointerup', { bubbles: true, pointerId: 9, pointerType: 'touch' })); }, k);
  const down = k => page.evaluate(k => document.querySelector(`#touch [data-k=${k}]`).dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, pointerId: 11, pointerType: 'touch' })), k);
  const up = k => page.evaluate(k => document.querySelector(`#touch [data-k=${k}]`).dispatchEvent(new PointerEvent('pointerup', { bubbles: true, pointerId: 11, pointerType: 'touch' })), k);
  await tap('enter'); await page.waitForTimeout(800);
  await page.evaluate(() => { const H = window.__havoc, pl = H.PLANES.list[0], p = H.HERO.p; p.x = pl.x - Math.cos(pl.yaw) * 3.5; p.z = pl.z + Math.sin(pl.yaw) * 3.5; });
  await page.waitForTimeout(500);
  console.log('prompt', await page.evaluate(() => document.querySelector('#prompt').textContent));
  await tap('enter'); await page.waitForTimeout(800);
  console.log('labels', await page.evaluate(() => [...document.querySelectorAll('#touch button')].map(b => b.dataset.k + ':' + b.textContent).join(' ')));
  await page.evaluate(() => { const H = window.__havoc, W = H.getW(), A = W.airport.site, pl = H.G.plane; const u = -310, v = 301; pl.x = A.ox + u * A.ux + v * A.vx; pl.z = A.oz + u * A.uz + v * A.vz; pl.yaw = Math.atan2(A.ux, A.uz); H.CAM.h = pl.yaw; });
  await down('gas'); await page.waitForTimeout(2500);
  console.log('throttle', await page.evaluate(() => { const pl = window.__havoc.G.plane; return [+pl.T.toFixed(2), +pl.gs.toFixed(1)]; }));
  await page.evaluate(() => { const pl = window.__havoc.G.plane; pl.gs = pl.def.vrot + 2; });
  await down('hand'); await page.waitForTimeout(2500); await up('hand'); await up('gas');
  console.log('climb', await page.evaluate(() => { const pl = window.__havoc.G.plane; return JSON.stringify({ gnd: pl.ground, alt: +(pl.y).toFixed(1), pitch: +pl.pitch.toFixed(2), T: +pl.T.toFixed(2) }); }));
  await page.screenshot({ path: SP + '/test/m3-fly.png' });
  console.log('errors', errs.length, errs.slice(0, 3).join('\n'));
  await browser.close();
})();
