const { chromium } = require('playwright');
const fs = require('fs');
const SP = process.argv[2], MAP = process.argv[3] || 'sand', TIME = process.argv[4] || 'night';
(async () => {
  const html = fs.readFileSync(SP + '/havoc/havoc-city.html', 'utf8');
  fs.writeFileSync(SP + '/test/index.html', '<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover"><style>body{margin:0}[hidden]{display:none!important}</style></head><body>' + html + '</body></html>');
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });
  const errs = [];
  page.on('console', m => { if (m.type() === 'error') errs.push(m.type() + ': ' + m.text()); });
  page.on('pageerror', e => errs.push('pageerror: ' + e.message + '\n' + e.stack));
  await page.route('**/three.min.js', r => r.fulfill({ path: SP + '/vendor/package/build/three.min.js', contentType: 'application/javascript' }));
  await page.route('**/fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
  await page.route('**/fonts.gstatic.com/**', r => r.abort());
  await page.goto('file://' + SP + '/test/index.html');
  await page.waitForTimeout(1500);
  await page.click(`.mapcard[data-map="${MAP}"]`);
  await page.evaluate((t) => { const H = window.__havoc; H.settings.time = t; H.settings.gore = 'high'; }, TIME);
  await page.click('#playBtn');
  await page.waitForTimeout(3000);
  const counts = () => page.evaluate(() => { const H = window.__havoc; const k = {}; for (const v of H.VEH.list) k[v.kind] = (k[v.kind] || 0) + 1; const P = H.G.player; return { kinds: k, peds: H.PED.list.filter(p => p.active).length, rag: H.PED.list.filter(p => p.active && p.rag).length, stars: H.wanted.stars, heli: H.HELI.active, player: { x: P.x.toFixed(1), z: P.z.toFixed(1), v: P.speed.toFixed(1), hp: P.health.toFixed(0) } }; });
  console.log('start', JSON.stringify(await counts()));
  await page.screenshot({ path: SP + '/test/10-start.png' });
  await page.keyboard.down('KeyW'); await page.waitForTimeout(2500); await page.keyboard.up('KeyW');
  // place 3 peds ahead and ram them
  await page.evaluate(() => {
    const H = window.__havoc, P = H.G.player; const fx = Math.sin(P.h), fz = Math.cos(P.h);
    const peds = H.PED.list.filter(p => p.active && !p.rag).slice(0, 3);
    peds.forEach((p, i) => { p.x = P.x + fx * (7 + i * 1.5) + (i - 1) * 0.6 * fz; p.z = P.z + fz * (7 + i * 1.5) - (i - 1) * 0.6 * fx; p.state = 'flee'; p.fleeT = 9; p.fx = -fz; p.fz = fx; p.run = 0.01; });
    P.vx = fx * 24; P.vz = fz * 24;
  });
  await page.waitForTimeout(300);
  await page.screenshot({ path: SP + '/test/11-hit.png' });
  await page.waitForTimeout(1500);
  console.log('after hit', JSON.stringify(await counts()));
  await page.evaluate(() => { const H = window.__havoc; H.CAM.mode = 1; const P = H.G.player; P.vx *= 0.1; P.vz *= 0.1; });
  await page.waitForTimeout(800);
  await page.screenshot({ path: SP + '/test/12-ragdoll.png' });
  await page.evaluate(() => { window.__havoc.addHeat(3.2, 3, true); });
  await page.keyboard.down('KeyW'); await page.waitForTimeout(6000);
  console.log('wanted', JSON.stringify(await counts()));
  await page.screenshot({ path: SP + '/test/13-chase.png' });
  await page.keyboard.up('KeyW'); await page.waitForTimeout(5000);
  await page.screenshot({ path: SP + '/test/14-chase2.png' });
  console.log('later', JSON.stringify(await counts()));
  await page.evaluate(() => { const H = window.__havoc, P = H.G.player; H.explode(P.x + Math.sin(P.h) * 9, P.y + 1, P.z + Math.cos(P.h) * 9, 1.2, P); });
  await page.waitForTimeout(250);
  await page.screenshot({ path: SP + '/test/15-boom.png' });
  await page.evaluate(() => { const H = window.__havoc, P = H.G.player; P.health = 1; H.explode(P.x, P.y + 1, P.z, 1, null); });
  await page.waitForTimeout(1200);
  await page.screenshot({ path: SP + '/test/16-wasted.png' });
  await page.waitForTimeout(4000);
  console.log('respawn', JSON.stringify(await counts()));
  await page.keyboard.press('Escape'); await page.waitForTimeout(400);
  await page.screenshot({ path: SP + '/test/17-pause.png' });
  await page.click('#pSettings'); await page.waitForTimeout(300);
  await page.screenshot({ path: SP + '/test/18-settings.png' });
  await page.click('#setClose'); await page.click('#pGarage'); await page.waitForTimeout(1200);
  await page.screenshot({ path: SP + '/test/19-garage.png' });
  console.log('errors:', errs.length); console.log(errs.slice(0, 12).join('\n'));
  await browser.close();
})();
