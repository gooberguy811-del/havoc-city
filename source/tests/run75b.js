const { chromium } = require('playwright');
const SP = process.argv[2];
(async () => {
  const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist'] });
  const ctx = await browser.newContext({ viewport: { width: 1000, height: 600 } }); const page = await ctx.newPage();
  await page.route('**/three.min.js', r => r.fulfill({ path: SP + '/vendor/package/build/three.min.js', contentType: 'application/javascript' }));
  await page.route('**/fonts.googleapis.com/**', r => r.fulfill({ body: '', contentType: 'text/css' }));
  await page.route('**/fonts.gstatic.com/**', r => r.abort());
  await page.goto('file://' + SP + '/test/index.html'); await page.waitForTimeout(800);
  await page.evaluate(() => Object.assign(window.__havoc.settings, { map: 'neon', quality: 'low', trafficDensity: 0, pedDensity: 0, police: 'off' }));
  await page.click('.mapcard[data-map="neon"]'); await page.click('#playBtn'); await page.waitForTimeout(3000);
  await page.evaluate(() => { const H = window.__havoc; if (!H.G.onFoot) H.toggleVehicle(); }); await page.waitForTimeout(1200);
  await page.keyboard.press('ControlLeft'); await page.waitForTimeout(200);
  const r = await page.evaluate(async () => { const H = window.__havoc, a = H.CAM.h; for (let i = 0; i < 5; i++) window.dispatchEvent(new MouseEvent('mousemove', { movementX: 40, movementY: 10, bubbles: true })); await new Promise(r => setTimeout(r, 300)); return { before: a, after: H.CAM.h, op: H.CAM.op, face: H.HERO.p.h }; });
  console.log('synthetic mouse move in shift-lock', JSON.stringify(r));
  await page.mouse.click(500, 300); await page.waitForTimeout(300);
  console.log('pointer lock after click:', await page.evaluate(() => !!document.pointerLockElement));
  await page.keyboard.press('KeyP'); await page.waitForTimeout(300);
  console.log('paused -> pointer lock:', await page.evaluate(() => !!document.pointerLockElement), 'pause visible', await page.evaluate(() => !document.getElementById('pause').hidden));
  await page.click('#resumeBtn'); await page.waitForTimeout(300);
  console.log('resumed -> pointer lock:', await page.evaluate(() => !!document.pointerLockElement));
  await page.keyboard.press('KeyM'); await page.waitForTimeout(300);
  console.log('map open -> pointer lock:', await page.evaluate(() => !!document.pointerLockElement));
  await browser.close();
})();
